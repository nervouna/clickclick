import Foundation

enum KeyCatalog {
    static func name(for key: HIDKeyID) -> String {
        if key.usagePage == 0x07 {
            return keyboardNames[key.usage] ?? String(format: "键 0x%02X", key.usage)
        }
        if key.usagePage == 0x0C {
            return consumerNames[key.usage] ?? String(format: "媒体键 0x%03X", key.usage)
        }
        return String(format: "HID 0x%02X:0x%02X", key.usagePage, key.usage)
    }

    static let keyboardRows: [[HIDKeyID]] = [
        keyRow([0x29, 0x3A, 0x3B, 0x3C, 0x3D, 0x3E, 0x3F, 0x40, 0x41, 0x42, 0x43, 0x44, 0x45]),
        keyRow([0x35, 0x1E, 0x1F, 0x20, 0x21, 0x22, 0x23, 0x24, 0x25, 0x26, 0x27, 0x2D, 0x2E, 0x2A]),
        keyRow([0x2B, 0x14, 0x1A, 0x08, 0x15, 0x17, 0x1C, 0x18, 0x0C, 0x12, 0x13, 0x2F, 0x30, 0x31]),
        keyRow([0x39, 0x04, 0x16, 0x07, 0x09, 0x0A, 0x0B, 0x0D, 0x0E, 0x0F, 0x33, 0x34, 0x28]),
        keyRow([0xE1, 0x1D, 0x1B, 0x06, 0x19, 0x05, 0x11, 0x10, 0x36, 0x37, 0x38, 0xE5]),
        keyRow([0xE0, 0xE3, 0xE2, 0x2C, 0xE6, 0xE7, 0xE4, 0x50, 0x51, 0x52, 0x4F])
    ]

    private static func keyRow(_ usages: [UInt16]) -> [HIDKeyID] {
        usages.map { HIDKeyID(usagePage: 0x07, usage: $0) }
    }

    private static let keyboardNames: [UInt16: String] = {
        var names: [UInt16: String] = [:]
        for (offset, letter) in "ABCDEFGHIJKLMNOPQRSTUVWXYZ".enumerated() {
            names[UInt16(0x04 + offset)] = String(letter)
        }
        let digits = ["1", "2", "3", "4", "5", "6", "7", "8", "9", "0"]
        for (offset, digit) in digits.enumerated() {
            names[UInt16(0x1E + offset)] = digit
        }
        names.merge([
            0x28: "回车", 0x29: "Esc", 0x2A: "Delete", 0x2B: "Tab", 0x2C: "空格",
            0x2D: "-", 0x2E: "=", 0x2F: "[", 0x30: "]", 0x31: "\\", 0x33: ";",
            0x34: "'", 0x35: "`", 0x36: ",", 0x37: ".", 0x38: "/", 0x39: "Caps Lock",
            0x46: "Print Screen", 0x47: "Scroll Lock", 0x48: "Pause", 0x49: "Insert",
            0x4A: "Home", 0x4B: "Page Up", 0x4C: "向前删除", 0x4D: "End",
            0x4E: "Page Down", 0x4F: "→", 0x50: "←", 0x51: "↓", 0x52: "↑",
            0xE0: "左 Control", 0xE1: "左 Shift", 0xE2: "左 Option", 0xE3: "左 Command",
            0xE4: "右 Control", 0xE5: "右 Shift", 0xE6: "右 Option", 0xE7: "右 Command"
        ]) { _, new in new }
        for index in 1...12 { names[UInt16(0x39 + index)] = "F\(index)" }
        return names
    }()

    private static let consumerNames: [UInt16: String] = [
        0x30: "电源", 0x32: "睡眠", 0x40: "菜单", 0x6F: "亮度 +", 0x70: "亮度 -",
        0x79: "键盘亮度 +", 0x7A: "键盘亮度 -", 0xB0: "播放", 0xB1: "暂停",
        0xB5: "下一首", 0xB6: "上一首", 0xB7: "停止", 0xCD: "播放/暂停",
        0xE2: "静音", 0xE9: "音量 +", 0xEA: "音量 -"
    ]
}
